-- Numerical Data Types
-- Numeric data types are used to store numeric values. There are three numeric data types in Python:
-- 1. int: This is used to store integer values.
-- 2. float: This is used to store decimal values.
-- 3. complex: This is used to store complex values.


-- 1. int
-- This is used to store integer values.
-- Example:
SELECT 10; -- Output: 10
SELECT -5; -- Output: -5
SELECT 0; -- Output: 0 

-- 2. float
-- This is used to store decimal values.
-- Example:
SELECT 3.14; -- Output: 3.14
SELECT -2.5; -- Output: -2.5
SELECT 0.0; -- Output: 0.0

-- 3. complex
-- This is used to store complex values.
-- Example:
SELECT 3 + 4j; -- Output: (3+4j)
SELECT -2j; -- Output: (-0+2j)