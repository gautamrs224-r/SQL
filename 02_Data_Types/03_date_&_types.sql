-- Date & Time Types
-- Date and time data types are used to store date and time values. There are two date and time data types in SQL:
-- 1. DATE: Stores date values in the format YYYY-MM-DD.
-- Example:
SELECT '2023-05-15'; -- Output: 2023-05-15

-- 2. TIME: Stores time values in the format HH:MM:SS.
-- Example:
SELECT '10:30:00'; -- Output: 10:30:00