-- Boolean data types are used to store logical values. There are two boolean values in SQL:
-- 1. True - represents the logical truth
-- example, you can create a boolean variable like this: is_valid = TRUE

-- 2. False - represents the logical false
-- example, you can create a boolean variable like this: is_valid = FALSE

-- Null data type is used to represent a value that is unknown or missing.
-- example, you can create a null variable like this: name = NULL
