-- 1. What is SQL ?
-- SQL (Structured Query Language) is a language for querying and manipulating data in a relational database management system (RDBMS). It is a standard for defining and executing queries on a database.

-- 2. Why do we need SQL ?
-- SQL is used to query and manipulate data in a database, which is a collection of structured information that is organized in tables, views, and other database objects.

-- 3. How do we use SQL ?
-- SQL is used to query and manipulate data in a database, which is a collection of structured information that is organized in tables, views, and other database objects.

-- 4. What is a database ?
-- A database is a collection of structured information that is organized in tables, views, and other database objects.

-- 5. What is a table ?
-- A table is a collection of rows and columns of data that is stored in a database.

-- 6. What is a row ?
-- A row is a collection of data that is stored in a table.

-- 7. What is a column ?
-- A column is a collection of data that is stored in a table.

-- 8. What is a view ?
-- A view is a virtual table that is created by a query on a database.

-- 9. What is a primary key ?
-- A primary key is a unique identifier for a row in a table.

-- 10. What is a foreign key ?
-- A foreign key is a column in a table that is used to link to the primary key of another table.

-- 11. What is a unique constraint ?
-- A unique constraint is a constraint that ensures that a column contains unique values.

-- 12. What is a not null constraint ?
-- A not null constraint is a constraint that ensures that a column cannot contain null values.

-- 13. What is a check constraint ?
-- A check constraint is a constraint that ensures that a column satisfies a specific condition.

-- 14. What is a default constraint ?
-- A default constraint is a constraint that specifies a default value for a column.

-- 15. What is a trigger ?
-- A trigger is a piece of code that is executed automatically when a specific event occurs in a database.

-- 16. What is a stored procedure ?
-- A stored procedure is a collection of SQL statements that is executed as a single unit.

-- 17. What is a function ?
-- A function is a collection of SQL statements that is executed as a single unit.

-- 18. What is a trigger ?
