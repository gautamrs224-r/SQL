-- Types
-- = : Equal to
-- != : Not equal to
-- > : Greater than
-- < : Less than
-- >= : Greater than or equal to
-- <= : Less than or equal to


USE startersql;

SELECT * FROM users WHERE id = 5;
SELECT * FROM users WHERE id != 5;
SELECT * FROM users WHERE id > 5;
SELECT * FROM users WHERE id < 5;
SELECT * FROM users WHERE id >= 5;
SELECT * FROM users WHERE id <= 5;